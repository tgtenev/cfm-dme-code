"""Common code for the catalog-distance check of the two-constant fit (Paper I section 4.2, Paper II section 6.1).

The boost law of Paper I, Eq. (8) (code T3 in refit_core.py), is fitted at fixed free volumes delta, with the scale a0
refitted at each by the ladder of refit_core.Ladder and every galaxy's mass-to-light ratios fitted under the 0.10 dex
priors of the sample of Paper I section 4.1 (153 galaxies, 3,168 points). A case is one input, one model and one
treatment of the distances and inclinations, tagged <input>-<model>-q<q>:
  input  'sparc', SPARC's tabulated Newtonian field, or 'model', the model's own Newtonian field of disks with
         thickness;
  model  'full', the exact AQUAL solutions in the disks, entered through Gamma in refit_core's 'corrected' mode, or
         'rel', the algebraic relation;
  q      'fit', distances and inclinations profiled within their catalog priors, or '1', both held at the catalog
         values.
catalog_distances_nodes.py writes one saved ladder per case and delta, and catalog_distances.py reads them.

Inputs, by paths from the repository root: data/sparc/SPARC_Lelli2016c.mrt and data/sparc/rotmod_ltg/; in this folder
aqual-refit-gamma-0.csv and aqual-refit-gamma-1.csv (Gamma at the prior centres) and aqual-refit-upsvar-0.csv,
aqual-refit-upsvar-1.csv, aqual-refit-upsvar2-0.csv and aqual-refit-upsvar2-1.csv (the direct solutions at other
mass-to-light ratios behind the 'corrected' mode), written by aqual-refit-solve.py, and aqual-disk-points.csv (the
points and the model's own field), written by aqual-disk-densities.py.
Output: the saved ladders, rotation-curves/catalog-distances-nodes/<tag>-d<delta>.json, one per case and delta. They
are regenerated by catalog_distances_nodes.py and are not deposited; git ignores the folder.
"""
import csv, json, math, os, re, sys
for _v in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ.setdefault(_v, "1")
sys.dont_write_bytecode = True
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))                  # rotation-curves/
ROOT = os.path.normpath(os.path.join(HERE, ".."))                  # the repository root
NODEDIR = os.path.join(HERE, "catalog-distances-nodes")            # the saved ladders, not deposited
sys.path.insert(0, HERE)
import refit_core as RC

GAMMA_FILES = [os.path.join(HERE, f"aqual-refit-gamma-{k}.csv") for k in (0, 1)]
UPSVAR = ([os.path.join(HERE, f"aqual-refit-upsvar-{k}.csv") for k in (0, 1)]
          + [os.path.join(HERE, f"aqual-refit-upsvar2-{k}.csv") for k in (0, 1)])

C_LIGHT = 2.99792458e8
MPC = 3.0856775814913673e22
OMEGA_L = 0.6847                 # Planck 2018, the value that Paper II section 2 adopts for H_dS
SQ_OL = math.sqrt(OMEGA_L)


def load():
    T1 = RC.read_table1(os.path.join(ROOT, "data/sparc/SPARC_Lelli2016c.mrt"))
    gals = RC.read_rotmod(os.path.join(ROOT, "data/sparc/rotmod_ltg"), T1)
    GAM = RC.read_gamma(GAMMA_FILES)
    PTS = RC.read_points(os.path.join(HERE, "aqual-disk-points.csv"))
    RC.attach(gals, GAM, PTS, strict=True)
    return T1, gals


def upsvar_rows():
    """As aqual-refit-fit.py upsvar_rows (the direct solutions behind the 'corrected' treatment). The files hold one
    column per case, named <law>_a<a0>_d<dlog Yd>_b<dlog Yb>, with <law> T11, the empirical function of McGaugh, Lelli
    and Schombert, nu(y) = 1/(1 - exp(-sqrt(y))), or T3d<delta>, the boost law at that free volume."""
    rows = []
    for p in UPSVAR:
        for r in csv.DictReader(open(p, encoding="utf-8-sig")):
            for k, v in r.items():
                m = re.fullmatch(r"(T11|T3d[0-9.]+)_a([0-9.]+e[+-][0-9]+)_d([+-][0-9.]+)_b([+-][0-9.]+)", k)
                if m and v != "":
                    rows.append(dict(galaxy=r["galaxy"], R=r["R"], law=m.group(1), a0=m.group(2), dlogYd=m.group(3),
                                     dlogYb=m.group(4), Gamma=v))
    return rows


def ctx(inp, full, delta):
    return dict(input=inp, law="T3", full=full, gmode="corrected", use_gok=True, delta=delta,
                nu=RC.law_nu("T3", delta))


def kappa(a0, delta, H0, dS=False):
    """(c H0/a0) ln(1 + delta); with dS, sqrt(Omega_L) times it, D ln(1 + delta) with the divisor D = c H_dS/a0. That
    is the counting factor kappa that the pair (delta, a0) implies (Paper II Eq. (2)), which the scale relation of the
    constrained fit sets to 1."""
    k = C_LIGHT * H0 * 1e3 / MPC / a0 * math.log1p(delta)
    return k * SQ_OL if dS else k


def case_tag(inp, model, qmode):
    return f"{inp}-{model}-q{qmode}"


def node_path(tag, delta):
    return os.path.join(NODEDIR, f"{tag}-d{delta:.6f}.json")


def load_nodes(tag):
    """All saved ladders of one case: {delta: saved ladder}."""
    out = {}
    pre = tag + "-d"
    if not os.path.isdir(NODEDIR):
        return out
    for fn in os.listdir(NODEDIR):
        if fn.startswith(pre) and fn.endswith(".json"):
            r = json.load(open(os.path.join(NODEDIR, fn), encoding="utf-8"))
            out[round(r["delta"], 6)] = r
    return out


def node_min(rec, w=None):
    """refit_core.Ladder.node_min on a saved ladder: parabola through the stored totals in log10 a0 (window 10), for
    galaxy weights w."""
    if "_ks" not in rec:
        ks_ = sorted(float(k) for k in rec["per"])
        per = {round(float(k), 6): np.array(v) for k, v in rec["per"].items()}
        rec["_ks"] = ks_
        rec["_P"] = np.array([per[round(k, 6)] for k in ks_])
    ks, P = rec["_ks"], rec["_P"]
    y = list(P @ w) if w is not None else list(P.sum(axis=1))
    r = RC.parab_ls(ks, y, 10)
    if r is None or r[0] < ks[0] or r[0] > ks[-1]:
        i = int(np.argmin(y))
        return y[i], ks[i]
    return r[1], r[0]
